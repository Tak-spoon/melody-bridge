const NOTE_TO_VAL: Record<string, number> = {
  C: 0, D: 1, E: 2, F: 3, G: 4, A: 5, B: 6
};

function c(id: string, note: string, oct: number): Card {
  const val = NOTE_TO_VAL[note];
  const absVal = (oct - 2) * 7 + val;
  return { id, val, oct, absVal };
}

